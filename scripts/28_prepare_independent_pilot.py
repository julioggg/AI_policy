def mod(filename,tag):
    p=Path(__file__).resolve().parent/filename
    spec=importlib.util.spec_from_file_location(tag,p)
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def within(path,parent):
    return path==parent or parent in path.parents


def safe(value):
    if value is None:return ""
    s=str(value).replace("\x00","").strip()
    if s.lower() in ("nan","none","nat"):return ""
    return ("'"+s) if s.startswith(("=","+","-","@")) else s


def filehash(path):
    sha=hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda:f.read(1024*1024),b""):
            sha.update(chunk)
    return sha.hexdigest()


def load_csv(path):
    with path.open(encoding="utf-8-sig",newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path,fields,rows):
    with path.open("w",encoding="utf-8-sig",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    path.chmod(0o600)


def load_frame(path,format_):
    if format_=="csv":
        data=load_csv(path)
    else:
        import pandas as pd
        df=pd.read_parquet(path,columns=[
            "openalex_id","title","abstract","publication_year","type","ai_decision"])
        data=df.where(pd.notnull(df),"").to_dict("records")
    required={"openalex_id","title","abstract","publication_year","type","ai_decision"}
    if any(not required.issubset(item) for item in data):
        raise ValueError("Source frame is missing mandatory bibliographic and original classification fields")
    result={}
    for row in data:
        id=str(row["openalex_id"]).strip()
        if not id or id.lower()=="nan":
            continue
        if id in result:continue
        result[id]=row
    return result


def validated_source(frame,old,phase05):
    original=load_csv(old)
    expected=sum(int(v["sample_n"]) for v in phase05["strata"].values())
    if len(original)!=expected or len({r.get("openalex_id","") for r in original})!=expected:
        raise ValueError("Original Phase05 sample key missing or duplicate")
    if not {"openalex_id","sample_id","stratum"}.issubset(original[0]):
        raise ValueError("Original Phase05 private key fields missing")
    actual_hash=hashlib.sha256(
        "\n".join(sorted(r["openalex_id"] for r in original)).encode("utf8")
    ).hexdigest()
    if actual_hash!=phase05.get("id_set_sha256"):
        raise ValueError("Old protected Phase05 sample does not match published identity fingerprint")
    observed_decisions=Counter(str(r["ai_decision"]).strip().lower() for r in frame.values())
    for group in ("screen_include_core","screen_include_policy","screen_include_context","screen_exclude"):
        decision="exclude" if group=="screen_exclude" else STRATA[group][0]
        if observed_decisions[decision]!=int(phase05["strata"][group]["population_n"]):
            raise ValueError("Original final screening population counts changed for "+group)
    if sum(observed_decisions.values())!=sum(int(phase05["strata"][g]["population_n"]) for g in ("screen_include_core","screen_include_policy","screen_include_context","screen_exclude")):
        raise ValueError("New or unknown machine screening classes found in frozen corpus")
    available={}
    for stratum,(decision,n) in STRATA.items():
        pool=sorted(k for k,r in frame.items()
                    if str(r["ai_decision"]).strip().lower()==decision)
        expected_n=int(phase05["strata"][stratum]["population_n"])
        if len(pool)!=expected_n:
            raise ValueError("Source CEDIA AI-screened stratum changed since Phase05 "+stratum)
        old_ids=set(r["openalex_id"] for r in original)
        unseen=[i for i in pool if i not in old_ids]
        if len(unseen)<n:
            raise ValueError("Insufficient NEW records for calibration in "+stratum)
        available[stratum]=unseen
    if sum(int(phase05["strata"][x]["population_n"]) for x in STRATA)>len(frame):
        raise ValueError("Source screening strata are not disjoint")
    if int(phase05["strata"]["screen_exclude"]["population_n"])!=18:
        raise ValueError("Phase05 excluded class has unexpected population size")
    return original,available


def select(available,seed):
    rng=random.Random(seed)
    picks=[]
    for stratum,(_,n) in STRATA.items():
        entries=available[stratum]
        for item in rng.sample(entries,n):
            picks.append((stratum,item))
    rng.shuffle(picks)
    return picks


